package com.example.data.repository

import android.util.Log
import com.google.firebase.Firebase
import com.google.firebase.ai.ai
import com.google.firebase.ai.type.content
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.TimeoutCancellationException
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withTimeout

private const val TAG = "AiRepository"

class AiRepository {
    private val model by lazy {
        Firebase.ai.generativeModel("gemini-3.8-flash")
    }

    fun generateStream(
        prompt: String,
        historyMessages: List<Pair<String, String>> = emptyList()
    ): Flow<String> = flow {
        try {
            val fullPrompt = buildString {
                appendLine("You are CLOUKE AI, the advanced generative assistant and software engineering intelligence powering the CLOUKE + Coltef platform.")
                appendLine("Provide insightful, production-grade, highly structured answers. Format code blocks using triple backticks with explicit language identifiers.")
                if (historyMessages.isNotEmpty()) {
                    appendLine("--- Previous Context ---")
                    for ((role, text) in historyMessages.takeLast(6)) {
                        appendLine("[$role]: $text")
                    }
                    appendLine("--- End Context ---")
                }
                appendLine("User: $prompt")
            }

            withTimeout(60_000L) {
                model.generateContentStream(fullPrompt).collect { chunk ->
                    val chunkText = chunk.text.orEmpty()
                    if (chunkText.isNotEmpty()) {
                        emit(chunkText)
                    }
                }
            }
        } catch (e: TimeoutCancellationException) {
            Log.e(TAG, "Streaming timed out after 60s", e)
            emit("\n[CLOUKE AI Notice: Request timed out. Please try again.]")
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Firebase AI streaming failed", e)
            emit("\n[CLOUKE AI Error: ${e.localizedMessage ?: "Failed to contact Gemini engine. Check network and App Check status."}]")
        }
    }

    suspend fun generateCodeAssistance(
        commandOrPrompt: String,
        currentFileContent: String,
        language: String
    ): String {
        return try {
            val prompt = """
                You are Coltef Code Intelligence inside CLOUKE.
                Language: $language
                Command / Instruction: $commandOrPrompt
                Current code:
                ```$language
                $currentFileContent
                ```
                Respond with the updated code or code analysis. Keep explanations concise and code ready to compile.
            """.trimIndent()

            val response = withTimeout(60_000L) {
                model.generateContent(prompt)
            }
            response.text ?: "// No response generated by model."
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Code assistance failed", e)
            "// Coltef Error: ${e.localizedMessage ?: "Failed to generate code."}"
        }
    }
}
